/**
 * 筆脈の道 ── 段ごとに切れた区間を、一本に繋いで見せるための座標。
 *
 * 脈は段（名乗り／作品／結び）をまたいで降りるが、段は別々の grid item なので
 * 一本の SVG では描けない。そこで区間ごとに viewBox="0 0 100 100" /
 * preserveAspectRatio="none" の箱を置き、
 *   x = 0   … 通り道の左端
 *   x = 100 … 通り道の右端
 * に固定する。箱の実寸が違っても x は同じ物理位置を指すので、
 * 区間の終点 x と次の区間の始点 x を揃えれば、繋ぎ目で折れずに一本に見える。
 *
 * ── なぜ dx（横送り）が要るか ────────────────────────────────
 * 区間の d は手で描いてあり、始点と終点の x が決まっている。作品が 2 件のときは
 * w1(→91) → w2(91→87) → w3(87→80) → tail(80→) と数値がちょうど噛み合うが、
 * 作品が増えると中間の区間を足すことになり、そのままでは繋ぎ目で飛ぶ。
 *
 * レジストリに 1 行足すだけで作品が増える、という構造を壊さないために、
 * 区間を translate で横へ送って始点を前の終点に合わせる。
 * 送り量はこの関数が計算する ── d を書き足す必要はない。
 *
 * ── 区間は【行】ではなく【段】に一つ（2026-09-20 に変えた）─────────
 * もとは作品の一行ごとに区間を一つ置いていた。目録に組み直して行が 16 → 19 に
 * 増えたところ、中間区間の送りが下限（FLOOR）に当たり続け、繋ぎ目で脈が
 * 飛ぶようになった ── 本番の 1280px でも、結びの手前で線が二本に割れていた
 * （最後の作品の区間が x=18 で終わり、結びが x=92 から始まっていた）。
 *
 * 区間を段に一つへ減らすと、手で描いた端点のまま素直に繋がる。一本の線が
 * 紙全体を降りる絵もむしろ強くなる ── viewBox は preserveAspectRatio="none"
 * なので、段が高いほど同じ曲線がゆっくり引き伸ばされる。
 * ＊ 2026-09-21 に全件を分類のページへ移したので、トップに残る段は
 *   「いま見てほしいもの」の一つだけ。区間は 頭 → w1 → 尾 の三本になった。
 *
 * ── 結びは【送り】ではなく【送りと伸縮】で合わせる ───────────────
 * 結びの区間だけは、始点を継ぎ目に合わせるだけでは足りない。終点は紙の左
 * （1 列目＝結びの版面の起点）に着かなければならないので、両端を同時に
 * 決める必要がある。translate だけではどちらか一方しか合わない ── もとの
 * 実装はここで送りを下限で打ち切っており、それが上の「飛び」の正体だった。
 * いまは x 方向の伸縮（tailScale）を併せて持たせ、始点は継ぎ目・終点は
 * 手で描いた着地点に、常に両方を合わせる。
 */

