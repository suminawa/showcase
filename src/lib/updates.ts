/** その品物の更新（新しい順） */
export function updatesFor(slug: string): KitUpdate[] {
  return UPDATES.filter((u) => u.slug === slug);
}

/** 「2026-09-28」→「2026.9.28」（更新の記録の日付） */
export function updateDate(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  return `${y}.${m}.${d}`;
}
